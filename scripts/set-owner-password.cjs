// Sets the hidden owner account's password (the account that controls trials and activation).
//
//   node scripts/set-owner-password.cjs            asks for the password
//   OWNER_PASSWORD=... node scripts/set-owner-password.cjs
//
// It rewrites electron/owner.cjs with a salted hash and a public key. The password itself is never
// written anywhere. Licences issued with the old password stop being valid in versions built afterwards.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const readline = require("readline");
const { deriveOwner } = require("../electron/license.cjs");

function write(password) {
  if (!password || password.length < 8) { console.error("The password must be at least 8 characters."); process.exit(1); }
  const file = path.join(__dirname, "..", "electron", "owner.cjs");
  let previous = {};
  try { previous = require(file); } catch (err) { previous = {}; }
  const salt = crypto.randomBytes(16).toString("hex");
  const d = deriveOwner(password, salt);
  const body = `// Generated by scripts/set-owner-password.cjs — do not edit the salt, hash or publicKey by hand.
// The hidden owner account: it is not stored in any database and does not appear anywhere in the app.
module.exports = {
  username: ${JSON.stringify(previous.username || "admin")},
  salt: "${salt}",
  hash: "${d.hash}",
  publicKey: "${d.publicKey}",
  // How long a new install works before the owner has to extend the trial or activate it.
  defaultTrialDays: ${Number(previous.defaultTrialDays) || 14},
};
`;
  fs.writeFileSync(file, body);
  console.log("electron/owner.cjs updated.");
}

if (process.env.OWNER_PASSWORD) write(process.env.OWNER_PASSWORD);
else {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  rl.question("New owner password: ", (answer) => { rl.close(); write(answer.trim()); });
}
